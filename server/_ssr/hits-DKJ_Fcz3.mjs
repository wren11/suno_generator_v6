function hitMatchesFilter(hit, filter) {
	if (filter === "All") return true;
	if (filter === "Now") return Boolean(hit.trending);
	const key = filter.toLowerCase();
	return hit.genres.some((g) => g.toLowerCase().includes(key) || key.includes(g.toLowerCase().split(" ")[0] ?? ""));
}
function hitsById(ids) {
	return ids.map((id) => HITS.find((h) => h.id === id)).filter((h) => Boolean(h));
}
function formatStreams(bn) {
	if (!bn) return null;
	return `${bn.toFixed(bn >= 10 ? 1 : 3).replace(/0+$/, "").replace(/\.$/, "")}B`;
}
